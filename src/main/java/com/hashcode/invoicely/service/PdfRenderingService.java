package com.hashcode.invoicely.service;

import com.hashcode.invoicely.dto.document.DesignDto;
import com.hashcode.invoicely.dto.document.PartsDto;
import lombok.extern.slf4j.Slf4j;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.PDPage;
import org.apache.pdfbox.pdmodel.PDPageContentStream;
import org.apache.pdfbox.pdmodel.common.PDRectangle;
import org.apache.pdfbox.pdmodel.font.PDType1Font;
import org.apache.pdfbox.pdmodel.font.Standard14Fonts;
import org.springframework.stereotype.Service;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.util.Map;

@Slf4j
@Service
public class PdfRenderingService {

    public byte[] generatePdf(String title, String body, Map<String, Object> meta) {
        try (PDDocument document = new PDDocument()) {
            PDPage page = new PDPage(PDRectangle.A4);
            document.addPage(page);

            try (PDPageContentStream content = new PDPageContentStream(document, page)) {
                content.beginText();
                content.setFont(new PDType1Font(Standard14Fonts.FontName.HELVETICA_BOLD), 18);
                content.newLineAtOffset(50, 780);
                content.showText(title != null ? title : "Invoicely Document");
                content.endText();

                content.setLineWidth(1.0f);
                content.moveTo(50, 765);
                content.lineTo(550, 765);
                content.stroke();

                content.beginText();
                content.setFont(new PDType1Font(Standard14Fonts.FontName.HELVETICA), 12);
                content.newLineAtOffset(50, 730);

                if (body != null && !body.isEmpty()) {
                    String[] lines = body.split("\n");
                    int lineCount = 0;
                    for (String line : lines) {
                        if (lineCount++ > 35) break; // stay on first page
                        String cleanLine = line.replaceAll("[\\r\\t]", " ").trim();
                        if (cleanLine.length() > 80) {
                            cleanLine = cleanLine.substring(0, 80);
                        }
                        content.showText(cleanLine);
                        content.newLineAtOffset(0, -18);
                    }
                } else {
                    content.showText("Generated by Invoicely Platform");
                    content.newLineAtOffset(0, -18);
                    content.showText("Status: Verified & Live");
                }
                content.endText();

                content.beginText();
                content.setFont(new PDType1Font(Standard14Fonts.FontName.HELVETICA_OBLIQUE), 9);
                content.newLineAtOffset(50, 40);
                content.showText("Invoicely Financial Architecture - Confidential");
                content.endText();
            }

            ByteArrayOutputStream baos = new ByteArrayOutputStream();
            document.save(baos);
            return baos.toByteArray();
        } catch (IOException e) {
            log.error("Failed to render PDF: {}", e.getMessage(), e);
            throw new RuntimeException("PDF generation failed: " + e.getMessage(), e);
        }
    }

    public byte[] renderDesign(DesignDto design, Map<String, Object> sampleData) {
        String name = design != null && design.getName() != null ? design.getName() : "Custom Design";
        PartsDto parts = design != null ? design.getDesign() : null;

        StringBuilder text = new StringBuilder();
        if (parts != null) {
            if (parts.getHeader() != null && !parts.getHeader().isEmpty()) {
                text.append("HEADER: ").append(stripHtml(parts.getHeader())).append("\n");
            }
            if (parts.getBody() != null && !parts.getBody().isEmpty()) {
                text.append("BODY: ").append(stripHtml(parts.getBody())).append("\n");
            }
            if (parts.getProduct() != null && !parts.getProduct().isEmpty()) {
                text.append("ITEMS: ").append(stripHtml(parts.getProduct())).append("\n");
            }
            if (parts.getFooter() != null && !parts.getFooter().isEmpty()) {
                text.append("FOOTER: ").append(stripHtml(parts.getFooter())).append("\n");
            }
        }

        if (text.isEmpty()) {
            text.append("Invoice Preview - ").append(name).append("\nSample preview rendered successfully.");
        }

        return generatePdf(name, text.toString(), sampleData);
    }

    private String stripHtml(String html) {
        if (html == null) return "";
        return html.replaceAll("<[^>]*>", " ").replaceAll("\\s+", " ").trim();
    }
}
